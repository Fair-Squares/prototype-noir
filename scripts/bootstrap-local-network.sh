#!/bin/sh
set -eu

ROOT_DIR="/workspace"
AZTEC_NODE_URL="${AZTEC_NODE_URL:-http://aztec:8080}"

log() {
  printf '\n[bootstrap] %s\n' "$1"
}

wait_for_pxe() {
  log "Waiting for Aztec PXE at ${AZTEC_NODE_URL}/status ..."
  until curl -sf "${AZTEC_NODE_URL}/status" > /dev/null 2>&1; do
    sleep 3
  done
  log "PXE is healthy ✓"
}

compile_contracts() {
  for c in kyc_verifier fund_token defi_vault housing_fund governance; do
    log "Compiling contract: ${c}"
    cd "${ROOT_DIR}/contracts/${c}"
    aztec compile || {
      log "WARN: 'aztec compile' not found in image, trying nargo..."
      nargo compile || {
        log "ERROR: Could not compile ${c}"
        exit 1
      }
    }
  done
}

deploy_contracts() {
  cd "${ROOT_DIR}"

  log "Importing test accounts..."
  aztec-wallet import-test-accounts 2>/dev/null || log "WARN: Could not import test accounts (may already exist)"

  # Deploy KYCVerifier
  log "Deploying KYCVerifier..."
  aztec-wallet deploy \
    "${ROOT_DIR}/contracts/kyc_verifier/target/kyc_verifier-KYCVerifier.json" \
    --from accounts:test0 \
    --args accounts:test0 \
    -a kyc_verifier 2>&1 || log "WARN: KYCVerifier deploy failed (may need manual deploy)"

  # Deploy FundToken
  log "Deploying FundToken..."
  aztec-wallet deploy \
    "${ROOT_DIR}/contracts/fund_token/target/fund_token-FundToken.json" \
    --from accounts:test0 \
    --args accounts:test0 \
    -a fund_token 2>&1 || log "WARN: FundToken deploy failed"

  # Deploy DeFiVault (300 bps = 3% APY)
  log "Deploying DeFiVault..."
  aztec-wallet deploy \
    "${ROOT_DIR}/contracts/defi_vault/target/defi_vault-DeFiVault.json" \
    --from accounts:test0 \
    --args accounts:test0 300 \
    -a defi_vault 2>&1 || log "WARN: DeFiVault deploy failed"

  # Deploy HousingFund
  log "Deploying HousingFund..."
  aztec-wallet deploy \
    "${ROOT_DIR}/contracts/housing_fund/target/housing_fund-HousingFund.json" \
    --from accounts:test0 \
    --args accounts:test0 \
    -a housing_fund 2>&1 || log "WARN: HousingFund deploy failed"

  # Deploy Governance (housing_fund placeholder = test0, council = test0)
  log "Deploying Governance..."
  aztec-wallet deploy \
    "${ROOT_DIR}/contracts/governance/target/governance-Governance.json" \
    --from accounts:test0 \
    --args accounts:test0 accounts:test0 \
    -a governance 2>&1 || log "WARN: Governance deploy failed"

  # Wire contracts together
  log "Wiring HousingFund.set_contracts..."
  aztec-wallet send set_contracts \
    --from accounts:test0 \
    --contract-address contracts:housing_fund \
    --args contracts:kyc_verifier contracts:fund_token contracts:defi_vault contracts:governance \
    2>&1 || log "WARN: set_contracts failed"

  log "Wiring DeFiVault.set_housing_fund..."
  aztec-wallet send set_housing_fund \
    --from accounts:test0 \
    --contract-address contracts:defi_vault \
    --args contracts:housing_fund \
    2>&1 || log "WARN: set_housing_fund failed"

  log "Wiring FundToken.set_admin → HousingFund..."
  aztec-wallet send set_admin \
    --from accounts:test0 \
    --contract-address contracts:fund_token \
    --args contracts:housing_fund \
    2>&1 || log "WARN: set_admin failed"
}

save_addresses() {
  log "Saving contract addresses to frontend/.env.local..."
  # Attempt to read addresses from aztec-wallet aliases
  cat > "${ROOT_DIR}/frontend/.env.local" << 'ENVEOF'
# Auto-generated by bootstrap-local-network.sh
NEXT_PUBLIC_AZTEC_PXE_URL=http://aztec:8080
NEXT_PUBLIC_DEV_MODE=true
NEXT_PUBLIC_SIMULATION=false

# Contract addresses (check `aztec-wallet get-alias` for actual values)
# These are populated by the bootstrap script
ENVEOF

  for alias in kyc_verifier fund_token defi_vault housing_fund governance; do
    addr=$(aztec-wallet get-alias "contracts:${alias}" 2>/dev/null || echo "DEPLOY_FAILED")
    upper=$(echo "${alias}" | tr '[:lower:]' '[:upper:]')
    echo "NEXT_PUBLIC_${upper}_ADDRESS=${addr}" >> "${ROOT_DIR}/frontend/.env.local"
  done

  log "Saved addresses to frontend/.env.local"
}

main() {
  wait_for_pxe
  compile_contracts
  deploy_contracts
  save_addresses
  log "════════════════════════════════════════════"
  log "Bootstrap completed ✓"
  log "Frontend: http://localhost:3000"
  log "Aztec PXE: ${AZTEC_NODE_URL}"
  log "════════════════════════════════════════════"
}

main
