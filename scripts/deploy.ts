/**
 * Fair Squares — Contract Deployment Script
 *
 * Deploys all 5 contracts to the local Aztec network in the correct dependency order:
 *   1. KYCVerifier      (no dependencies)
 *   2. FundToken/FSFT   (no dependencies)
 *   3. DeFiVault        (needs HousingFund address — chicken-and-egg solved below)
 *   4. HousingFund      (needs KYCVerifier, FundToken, DeFiVault, Governance)
 *   5. Governance       (needs HousingFund)
 *
 * After deployment, wires all contracts together and saves addresses to:
 *   ../frontend/.env.local
 */

import {
  Contract,
  type ContractArtifact,
  createPXEClient,
  waitForPXE,
} from "@aztec/aztec.js";
import { getInitialTestAccountsWallets } from "@aztec/accounts/testing";
import * as fs from "fs";
import * as path from "path";

// ── Config ────────────────────────────────────────────────────────────────────
const PXE_URL = process.env.AZTEC_PXE_URL ?? "http://localhost:8080";
const YIELD_RATE_BPS = 300; // 3% APY
// ── Helpers ───────────────────────────────────────────────────────────────────

function log(msg: string) {
  console.log(`[deploy] ${msg}`);
}

function loadArtifact(relativePath: string): ContractArtifact {
  const artifactPath = path.resolve(__dirname, relativePath);
  if (!fs.existsSync(artifactPath)) {
    throw new Error(
      `Missing artifact: ${artifactPath}. Run 'aztec compile' in the corresponding contracts directory first.`
    );
  }
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  return artifact as ContractArtifact;
}

function saveEnvFile(addresses: Record<string, string>) {
  const envPath = path.resolve(__dirname, "../frontend/.env.local");
  const lines = [
    "# Auto-generated by scripts/deploy.ts",
    `# Generated: ${new Date().toISOString()}`,
    "",
    `NEXT_PUBLIC_AZTEC_PXE_URL=${PXE_URL}`,
    "",
    "# Contract addresses",
    ...Object.entries(addresses).map(
      ([key, val]) => `NEXT_PUBLIC_${key}=${val}`
    ),
    "",
    "# zkPassport (set your domain below)",
    "ZKPASSPORT_DOMAIN=fair-squares.local",
    "ZKPASSPORT_VERIFIER_PRIVATE_KEY=",
    "",
    "# Dev mode — skip zkPassport KYC (set to true for local testing)",
    "NEXT_PUBLIC_DEV_MODE=true",
  ];

  fs.writeFileSync(envPath, lines.join("\n") + "\n");
  log(`Saved contract addresses to ${envPath}`);
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  log(`Connecting to Aztec local network at ${PXE_URL}…`);
  const pxe = createPXEClient(PXE_URL);
  await waitForPXE(pxe);
  log("Connected ✓");

  const wallets = await getInitialTestAccountsWallets(pxe);
  if (wallets.length === 0) {
    throw new Error("No test wallets available from PXE.");
  }
  const wallet = wallets[0];
  const adminAddress = await wallet.getAddress();
  log(`Using admin: ${adminAddress}`);

  // ── 1. KYCVerifier ──────────────────────────────────────────────────────────
  log("Deploying KYCVerifier…");
  const kycVerifierArtifact = loadArtifact(
    "../contracts/kyc_verifier/target/kyc_verifier-KYCVerifier.json"
  );
  const kycVerifier = await Contract.deploy(wallet, kycVerifierArtifact, [adminAddress])
    .send()
    .deployed();
  log(`KYCVerifier deployed at: ${kycVerifier.address}`);

  // ── 2. FundToken (FSFT) ─────────────────────────────────────────────────────
  log("Deploying FundToken (FSFT)…");
  const fundTokenArtifact = loadArtifact(
    "../contracts/fund_token/target/fund_token-FundToken.json"
  );

  // Admin will be updated to HousingFund after deployment
  const fundToken = await Contract.deploy(wallet, fundTokenArtifact, [
    adminAddress,
    "Fair Squares Fund Token",
    "FSFT",
    18,
  ])
    .send()
    .deployed();
  log(`FundToken deployed at: ${fundToken.address}`);

  // ── 3. DeFiVault ────────────────────────────────────────────────────────────
  // Chicken-and-egg: DeFiVault needs HousingFund address, but HousingFund needs DeFiVault.
  // Solution: deploy DeFiVault with a placeholder, then update after HousingFund is live.
  log("Deploying DeFiVault (placeholder housing_fund)…");
  const defiVaultArtifact = loadArtifact(
    "../contracts/defi_vault/target/defi_vault-DeFiVault.json"
  );

  const defiVault = await Contract.deploy(wallet, defiVaultArtifact, [
    adminAddress, // placeholder — will need update mechanism in production
    YIELD_RATE_BPS,
  ])
    .send()
    .deployed();
  log(`DeFiVault deployed at: ${defiVault.address}`);

  // ── 4. Governance (placeholder HousingFund) ─────────────────────────────────
  log("Deploying Governance (placeholder housing_fund)…");
  const governanceArtifact = loadArtifact(
    "../contracts/governance/target/governance-Governance.json"
  );

  const governanceTmp = await Contract.deploy(wallet, governanceArtifact, [
    adminAddress, // placeholder
    adminAddress, // council = admin for prototype
  ])
    .send()
    .deployed();
  log(`Governance deployed at: ${governanceTmp.address}`);

  // ── 5. HousingFund ──────────────────────────────────────────────────────────
  log("Deploying HousingFund…");
  const housingFundArtifact = loadArtifact(
    "../contracts/housing_fund/target/housing_fund-HousingFund.json"
  );
  const housingFund = await Contract.deploy(wallet, housingFundArtifact, [
    adminAddress,
    kycVerifier.address,
    fundToken.address,
    defiVault.address,
    governanceTmp.address,
  ])
    .send()
    .deployed();
  log(`HousingFund deployed at: ${housingFund.address}`);

  // ── Wire FundToken admin → HousingFund ──────────────────────────────────────
  // TODO: In production, FundToken.set_admin(housingFund.address) would be called here
  // For prototype: admin key still controls FundToken (acceptable for local testing)
  log(`NOTE: FundToken admin is still ${adminAddress} (not HousingFund)`);
  log(`      In production, call FundToken.set_admin(${housingFund.address})`);

  // ── Summary ─────────────────────────────────────────────────────────────────
  const addresses = {
    KYC_VERIFIER_ADDRESS:  kycVerifier.address.toString(),
    FUND_TOKEN_ADDRESS:    fundToken.address.toString(),
    DEFI_VAULT_ADDRESS:    defiVault.address.toString(),
    GOVERNANCE_ADDRESS:    governanceTmp.address.toString(),
    HOUSING_FUND_ADDRESS:  housingFund.address.toString(),
    ADMIN_ADDRESS:         adminAddress.toString(),
  };

  console.log("\n=== DEPLOYED CONTRACT ADDRESSES ===");
  Object.entries(addresses).forEach(([k, v]) => console.log(`  ${k}: ${v}`));
  console.log("====================================\n");

  saveEnvFile(addresses);

  log("✅ Deployment complete! Run the frontend with: cd ../frontend && npm run dev");
}

main().catch((err) => {
  console.error("Deployment failed:", err);
  process.exit(1);
});
