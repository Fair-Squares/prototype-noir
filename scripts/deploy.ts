/**
 * Fair Squares — Contract Deployment Script (v4 API)
 *
 * Alternative to the shell-based bootstrap. Uses the Aztec JS SDK directly.
 *
 * Usage:
 *   cd scripts && npm install && npx tsx deploy.ts
 *
 * Requires: Aztec local network running at AZTEC_NODE_URL (default: http://localhost:8080)
 * Requires: Contracts compiled (run `aztec compile` in each contract directory first)
 */

import { AztecAddress } from "@aztec-labs/aztec.js/addresses";
import { createAztecNodeClient } from "@aztec-labs/aztec.js/node";
import { getInitialTestAccountsData } from "@aztec-labs/accounts/testing";
import { EmbeddedWallet } from "@aztec-labs/wallets/embedded";
import * as fs from "fs";
import * as path from "path";

// ── Config ────────────────────────────────────────────────────────────────────
const NODE_URL = process.env.AZTEC_NODE_URL ?? process.env.PXE_URL ?? "http://localhost:8080";

function log(msg: string) {
  console.log(`[deploy] ${msg}`);
}

function loadArtifact(relativePath: string): any {
  const artifactPath = path.resolve(__dirname, relativePath);
  if (!fs.existsSync(artifactPath)) {
    throw new Error(
      `Missing artifact: ${artifactPath}. Run 'aztec compile' in the corresponding contracts directory first.`
    );
  }
  return JSON.parse(fs.readFileSync(artifactPath, "utf8"));
}

function saveEnvFile(addresses: Record<string, string>) {
  const envPath = path.resolve(__dirname, "../frontend/.env.local");
  const lines = [
    "# Auto-generated by scripts/deploy.ts",
    `# Generated: ${new Date().toISOString()}`,
    "",
    `NEXT_PUBLIC_AZTEC_PXE_URL=${NODE_URL}`,
    "NEXT_PUBLIC_DEV_MODE=true",
    "NEXT_PUBLIC_SIMULATION=false",
    "",
    "# Contract addresses",
    ...Object.entries(addresses).map(
      ([key, val]) => `NEXT_PUBLIC_${key}=${val}`
    ),
    "",
    "# zkPassport (set your domain below)",
    "ZKPASSPORT_DOMAIN=fair-squares.local",
    "NEXT_PUBLIC_DEV_MODE=true",
  ];

  fs.writeFileSync(envPath, lines.join("\n") + "\n");
  log(`Saved contract addresses to ${envPath}`);
}

// ── Main ──────────────────────────────────────────────────────────────────────

async function main() {
  log(`Connecting to Aztec local network at ${NODE_URL}…`);
  const node = createAztecNodeClient(NODE_URL);

  log("Creating wallet...");
  const wallet = await EmbeddedWallet.create(node);

  const [adminData] = await getInitialTestAccountsData();
  // Aztec >= 5: the signing key is the account root (it is no longer derived
  // from the privacy secret), so it must be passed explicitly.
  const adminAccount = await wallet.createSchnorrAccount(
    adminData.secret,
    adminData.salt,
    adminData.signingKey
  );
  const adminAddress = adminAccount.address;
  log(`Using admin: ${adminAddress}`);

  // Note: This deploy script is a template for the v4 JS API.
  // The preferred method is using `aztec-wallet deploy` CLI commands
  // (see bootstrap-local-network.sh) which handles artifact loading natively.
  //
  // For programmatic deployment with codegen'd TypeScript contract classes:
  //   1. aztec compile (in each contract dir)
  //   2. aztec codegen target --outdir artifacts (in each contract dir)
  //   3. import { ContractClass } from "./artifacts/ContractName.js"
  //   4. await ContractClass.deploy(wallet).send({ from: adminAddress })

  log("⚠️  For full deployment, use: docker compose --profile aztec up");
  log("    The bootstrap container handles compile + deploy automatically.");

  const addresses = {
    ADMIN_ADDRESS: adminAddress.toString(),
  };

  console.log("\n=== ADMIN ACCOUNT ===");
  Object.entries(addresses).forEach(([k, v]) => console.log(`  ${k}: ${v}`));
  console.log("=====================\n");

  saveEnvFile(addresses);
}

main().catch((err) => {
  console.error("Deployment failed:", err);
  process.exit(1);
});
