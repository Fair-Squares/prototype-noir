// -- Public API ---------------------------------------------------------------

export async function getLiveAccounts(): Promise<string[]> {
  const wallet = await getWallet();
  if (typeof wallet.getRegisteredAccounts === "function") {
    const accounts = await wallet.getRegisteredAccounts();
    return accounts.map((a: any) =>
      typeof a === "string" ? a : a.address?.toString() ?? String(a)
    );
  }

  // Fallback: return admin address from env
  const addrs = getContractAddresses();
  return addrs.admin ? [addrs.admin] : [];
}

export async function getLiveKycStatus(address: string): Promise<boolean> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const kyc = await getKYCVerifierContract();
  const { AztecAddress } = await loadAztecAddress();
  const userAddr = AztecAddress.fromString(address);

  const result = await kyc.methods.is_verified(userAddr).simulate();
  return Boolean(result);
}

export async function registerLiveKyc(userAddress: string): Promise<void> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const kyc = await getKYCVerifierContract();
  const { AztecAddress } = await loadAztecAddress();
  const userAddr = AztecAddress.fromString(userAddress);
  const addrs = getContractAddresses();

  await kyc.methods.register_kyc(userAddr).send({
    from: AztecAddress.fromString(addrs.admin),
  });
}

export async function getLiveFundStats(): Promise<{
  totalDeposits: number;
  totalInDefi: number;
  totalAllocated: number;
  available: number;
  totalYield: number;
  isPaused: boolean;
  investorCount: number;
  totalSupply: number;
}> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const housingFund = await getHousingFundContract();
  const defiVault = await getDeFiVaultContract();
  const fundToken = await getFundTokenContract();
  const kyc = await getKYCVerifierContract();

  // Read from HousingFund
  const fundStats = await housingFund.methods.get_fund_stats().simulate();
  const [totalDeposits, totalInDefi, totalAllocated, available] = fundStats;
  const isPaused = await housingFund.methods.is_paused().simulate();

  // Read from DeFiVault
  const accruedYield = await defiVault.methods.get_accrued_yield().simulate();

  // Read from FundToken
  const totalSupply = await fundToken.methods.total_supply().simulate();

  // Read from KYCVerifier
  const investorCount = await kyc.methods.get_verified_count().simulate();

  return {
    totalDeposits: Number(totalDeposits),
    totalInDefi: Number(totalInDefi),
    totalAllocated: Number(totalAllocated),
    available: Number(available),
    totalYield: Number(accruedYield),
    isPaused: Boolean(isPaused),
    investorCount: Number(investorCount),
    totalSupply: Number(totalSupply),
  };
}

