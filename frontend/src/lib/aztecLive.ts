/**
 * Aztec live-mode integration for Fair Squares.
 *
 * When AZTEC_LIVE=true, API routes call these functions to interact with
 * real deployed contracts via the Aztec PXE. Falls back to simulation on error.
 *
 * Contract interaction uses generated TypeScript wrappers (from `aztec codegen`)
 * located in frontend/src/artifacts/. The bootstrap container generates these
 * before the frontend starts.
 */

import { getWallet, getPxeUrl } from "./aztecClient";
import type { AztecAddress } from "@aztec/aztec.js/addresses";

export function isLiveModeEnabled(): boolean {
  // IMPORTANT: Use only non-NEXT_PUBLIC_ variables here.
  // NEXT_PUBLIC_* values are baked into the bundle at build time by webpack,
  // so runtime .env.local changes don't affect them in server code.
  // AZTEC_LIVE is a true runtime server-only env var.
  return process.env.AZTEC_LIVE === "true";
}

// -- Contract addresses from env (set by bootstrap) ---------------------------

export function getContractAddresses() {
  return {
    kycVerifier: process.env.NEXT_PUBLIC_KYC_VERIFIER_ADDRESS ?? "",
    fundToken: process.env.NEXT_PUBLIC_FUND_TOKEN_ADDRESS ?? "",
    defiVault: process.env.NEXT_PUBLIC_DEFI_VAULT_ADDRESS ?? "",
    housingFund: process.env.NEXT_PUBLIC_HOUSING_FUND_ADDRESS ?? "",
    governance: process.env.NEXT_PUBLIC_GOVERNANCE_ADDRESS ?? "",
    admin: process.env.NEXT_PUBLIC_ADMIN_ADDRESS ?? "",
  };
}

function hasValidAddresses(): boolean {
  const addrs = getContractAddresses();
  return (
    !!addrs.housingFund &&
    addrs.housingFund !== "DEPLOY_FAILED" &&
    !!addrs.kycVerifier &&
    addrs.kycVerifier !== "DEPLOY_FAILED"
  );
}

// -- Dynamic contract imports -------------------------------------------------
// Generated by `aztec codegen` during bootstrap. These may not exist during
// development without Docker, so we use dynamic imports with error handling.

async function loadAztecAddress(): Promise<{ AztecAddress: typeof AztecAddress }> {
  return await import("@aztec/aztec.js/addresses");
}

async function getHousingFundContract() {
  const wallet = await getWallet();
  const { AztecAddress } = await loadAztecAddress();
  const addrs = getContractAddresses();
  const addr = AztecAddress.fromString(addrs.housingFund);

  // Try generated wrapper first
  try {
    const mod = await import("@/artifacts/HousingFund");
    const ContractClass = mod.HousingFundContract ?? mod.default;
    return await ContractClass.at(addr, wallet);
  } catch {
    // Generated wrapper not available -- this is expected during development
    throw new Error("HousingFund contract wrapper not generated yet");
  }
}

