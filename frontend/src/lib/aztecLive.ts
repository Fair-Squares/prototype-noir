export async function getLivePortfolio(address: string): Promise<{
  balance: number;
  totalSupply: number;
  sharePercent: number;
  estimatedYield: number;
}> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const fundToken = await getFundTokenContract();
  const { AztecAddress } = await loadAztecAddress();
  const userAddr = AztecAddress.fromString(address);

  const balance = await fundToken.methods.public_balance_of(userAddr).simulate();
  const totalSupply = await fundToken.methods.total_supply().simulate();

  const balanceNum = Number(balance);
  const supplyNum = Number(totalSupply);
  const sharePercent = supplyNum > 0 ? (balanceNum / supplyNum) * 100 : 0;
  const estimatedYield = balanceNum * 0.03; // 3% APY estimate

  return {
    balance: balanceNum,
    totalSupply: supplyNum,
    sharePercent: Math.round(sharePercent * 100) / 100,
    estimatedYield: Math.round(estimatedYield * 100) / 100,
  };
}

export async function getLiveProposals(): Promise<
  Array<{
    id: number;
    descHash: string;
    amount: number;
    yesVotes: number;
    noVotes: number;
    status: number;
  }>
> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const gov = await getGovernanceContract();
  const count = await gov.methods.get_proposal_count().simulate();
  const proposals = [];

  for (let i = 0; i < Number(count); i++) {
    const result = await gov.methods.get_proposal(i).simulate();
    const [descHash, amount, yesVotes, noVotes, status] = result;
    proposals.push({
      id: i,
      descHash: String(descHash),
      amount: Number(amount),
      yesVotes: Number(yesVotes),
      noVotes: Number(noVotes),
      status: Number(status),
    });
  }

  return proposals;
}

export async function liveCastVote(
  address: string,
  proposalId: number,
  voteYes: boolean
): Promise<void> {
  if (!hasValidAddresses()) {
    throw new Error("Contract addresses not configured");
  }

  const gov = await getGovernanceContract();
  const { AztecAddress } = await loadAztecAddress();

  await gov.methods.cast_vote(proposalId, voteYes).send({
    from: AztecAddress.fromString(address),
  });
}
